"""Генерирует набор примеров выписок в разных «банковских» стилях.

Каждый файл проверяет свою особенность формата (названия колонок, статусы,
служебные строки, второй лист, отсутствие номера документа).

Нужен openpyxl:  pip install openpyxl
Запуск:          python fixtures/make_bank_examples.py

Все реквизиты и суммы вымышленные.
"""
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

OUT = Path(__file__).resolve().parent / "примеры"

THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
MONEY = "#,##0.00"
HEAD_FILL = PatternFill("solid", fgColor="DCE6F1")
TITLE_FONT = Font(bold=True, size=12)


def write_table(ws, header_row, header, rows, widths, money_col):
    """Шапка таблицы + строки с оформлением. Возвращает первую свободную строку."""
    for col, title in enumerate(header, start=1):
        c = ws.cell(row=header_row, column=col, value=title)
        c.font = Font(bold=True)
        c.fill = HEAD_FILL
        c.border = BORDER
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    r = header_row
    for row in rows:
        r += 1
        for col, value in enumerate(row, start=1):
            c = ws.cell(row=r, column=col, value=value)
            c.border = BORDER
            if col == money_col and isinstance(value, (int, float)):
                c.number_format = MONEY
                c.alignment = Alignment(horizontal="right")
            elif col == money_col and isinstance(value, str):
                c.number_format = MONEY
                c.alignment = Alignment(horizontal="right")

    for col, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(col)].width = width
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)
    return r + 1


def write_info(ws, title, info):
    """«Шапка» банка: название, реквизиты, период — над таблицей."""
    ws["A1"] = title
    ws["A1"].font = TITLE_FONT
    for i, (label, value) in enumerate(info, start=2):
        ws.cell(row=i, column=1, value=label).font = Font(bold=True)
        ws.cell(row=i, column=2, value=value)
    return len(info) + 3  # одна пустая строка перед таблицей


