THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
MONEY = "#,##0.00"
HEAD_FILL = PatternFill("solid", fgColor="DCE6F1")
TITLE_FONT = Font(bold=True, size=12)


def build() -> None:
    wb = Workbook()

    # ── лист 1: выписка ────────────────────────────────────────────────
    ws = wb.active
    ws.title = "Выписка"

    info = [
        ("АО «Пример-Банк»", ""),
        ("БИК", "044525225"),
        ("Корр. счёт", "30101810400000000225"),
        ("Организация", "ООО «Ваша Компания»"),
        ("ИНН / КПП", "7701234567 / 770101001"),
        ("Расчётный счёт", "40702810600000001234"),
        ("Период", "01.10.2026 – 15.10.2026"),
        ("Остаток на начало периода", "1 250 000,00 RUB"),
    ]
    ws["A1"] = "Выписка по расчётному счёту"
    ws["A1"].font = TITLE_FONT
    for i, (label, value) in enumerate(info, start=2):
        ws.cell(row=i, column=1, value=label).font = Font(bold=True)
        ws.cell(row=i, column=2, value=value)

    header_row = len(info) + 3  # одна пустая строка перед таблицей
    for col, title in enumerate(HEADER, start=1):
        c = ws.cell(row=header_row, column=col, value=title)
        c.font = Font(bold=True)
        c.fill = HEAD_FILL
        c.border = BORDER
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

    for r, row in enumerate(ROWS, start=header_row + 1):
        for col, value in enumerate(row, start=1):
            c = ws.cell(row=r, column=col, value=value)
            c.border = BORDER
            if col == 8 and isinstance(value, str) and value.replace(" ", "").replace(",", "").isdigit():
                c.number_format = MONEY
                c.alignment = Alignment(horizontal="right")

    widths = (14, 14, 16, 13, 28, 15, 46, 14, 8, 20)
    for col, width in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(col)].width = width
    ws.freeze_panes = ws.cell(row=header_row + 1, column=1)

    # ── лист 2: обороты (типичный второй лист выгрузки) ────────────────
    ws2 = wb.create_sheet("Обороты по счёту")
    ws2["A1"] = "Обороты по счёту за период"
    ws2["A1"].font = TITLE_FONT
    ws2.append([])
    ws2.append(["Показатель", "Сумма"])
    for row in [
        ["Остаток на начало периода", "1 250 000,00"],
        ["Обороты по дебету", "564 576,30"],
        ["Обороты по кредиту", "547 250,40"],
        ["Остаток на конец периода", "1 232 674,10"],
    ]:
        ws2.append(row)
    ws2.column_dimensions["A"].width = 30
    ws2.column_dimensions["B"].width = 16

    wb.save(str(OUT))
    print("создан:", OUT)


if __name__ == "__main__":
    build()
