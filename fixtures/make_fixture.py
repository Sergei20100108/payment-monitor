from datetime import datetime
from pathlib import Path

from openpyxl import Workbook

OUT = Path(__file__).resolve().parent

HEADER = ["Дата операции", "Номер документа", "Контрагент",
          "Назначение платежа", "Сумма", "Валюта", "Статус"]

# 1-я выгрузка
ROWS_1 = [
    ["01.10.2026", "ПП-001", "ООО Ромашка", "Оплата по договору №45", "15 000,00", "RUB", "Исполнено"],
    ["02.10.2026", "ПП-002", "ИП Иванов И.И.", "Аренда офиса за октябрь", "1 234,56", "RUB", "В обработке"],
    ["03.10.2026", "ПП-003", "АО Техносервис", "Поставка оборудования (счёт 77)", 9999.99, "RUB", "Отклонено"],
    [datetime(2026, 10, 5), "ПП-004", "ООО Ромашка", "Возврат по договору №45", "(5 000,00)", "RUB", "Возврат"],
    ["Итого по документу", None, None, None, 21234.55, "RUB", None],  # должна быть пропущена
]

# 2-я выгрузка: те же платежи с изменившимися статусами + один новый
# (даты операций сохраняем — так выглядит повторная выгрузка реального банка)
ROWS_2 = [
    ["01.10.2026", "ПП-001", "ООО Ромашка", "Оплата по договору №45", "15 000,00", "RUB", "Исполнено"],
    ["02.10.2026", "ПП-002", "ИП Иванов И.И.", "Аренда офиса за октябрь", "1 234,56", "RUB", "Исполнено"],
    ["03.10.2026", "ПП-003", "АО Техносервис", "Поставка оборудования (счёт 77)", 9999.99, "RUB", "Отменено"],
    [datetime(2026, 10, 5), "ПП-004", "ООО Ромашка", "Возврат по договору №45", "(5 000,00)", "RUB", "Возврат"],
    ["06.10.2026", "ПП-005", "ООО Космос", "Новая поставка по счёту 101", "42 000,00", "RUB", "Исполнено"],
]

# 3-я выгрузка: ещё один платёж (для проверки мониторинга папки)
ROWS_3 = ROWS_2 + [
    ["07.10.2026", "ПП-006", "ООО Спектр", "Оплата услуг связи", "3 500,50", "RUB", "В обработке"],
]


def build(path: Path, rows) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Выписка"
    ws.append(["Выписка по расчётному счёту за октябрь 2026"])  # «шапка» банка
    ws.append([])
    ws.append(HEADER)
    for r in rows:
        ws.append(r)
    for col, width in zip("ABCDEFG", (14, 16, 22, 40, 14, 8, 14)):
        ws.column_dimensions[col].width = width
    wb.save(str(path))
    print("создан:", path.name)


if __name__ == "__main__":
    build(OUT / "выписка_1.xlsx", ROWS_1)
    build(OUT / "выписка_2.xlsx", ROWS_2)
    build(OUT / "выписка_3.xlsx", ROWS_3)
